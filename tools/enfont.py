CHARS = ''.join(sorted(G))


def cell(a, b):
    """Return 11 rows x 12 bits (as ints) for the pair (a, b)."""
    # The renderer also draws the previous slot's bottom row above each glyph, so the
    # letters are moved up one pixel to keep the bottom row (row 10) empty.
    rows = []
    for y in range(11):
        bits = 0
        if y == 10:
            rows.append(0)
            continue
        for x, ch in enumerate(G[a][y + 1] + '.' + G[b][y + 1] + '.'):
            if ch == '#':
                bits |= 1 << (15 - x)       # MSB-first in a 16-bit row
        rows.append(bits)
    return rows
